export default async function run(page) {
  const results = {}
  await page.goto('http://127.0.0.1:5173/')
  await page.getByRole('link', { name: 'Mali' }).click()
  await page.getByRole('heading', { name: 'Mali', exact: true }).waitFor()
  results.countryFlagSelectsCorrectBranch = await page.locator('.country-detail').innerText().then((text) => text.includes('ml.keina@keinagroup.com'))
  await page.goto('http://127.0.0.1:5173/partners/login')
  await page.getByLabel('Clé d’accès partenaire').fill('AniekPartner2024!')
  await page.getByRole('button', { name: 'Se connecter' }).click()
  await page.waitForURL('**/partners')
   await page.waitForFunction(() => document.querySelectorAll('.partner-card').length > 0)
  results.partnerRedirect = page.url().endsWith('/partners')
  results.partnerCards = await page.locator('.partner-card').count()

  await page.getByRole('searchbox').fill('wurth')
  await page.waitForFunction(() => document.querySelectorAll('.partner-card').length === 1)
  results.accentInsensitiveSearch = await page.locator('.partner-card').innerText()
  await page.getByRole('button', { name: 'Voir les 11 fiches' }).click()
  await page.waitForSelector('.team-modal')
  await page.locator('.team-modal img').evaluate((image) => image.decode())
  results.teamSheetCount = await page.locator('.team-modal img').count()
  await page.getByRole('button', { name: 'Suivant' }).click()
  results.teamViewerAdvances = (await page.locator('.modal-header').innerText()).includes('Fiche 2 / 11')
  await page.getByRole('button', { name: 'Fermer' }).click()
  await page.getByRole('button', { name: 'Déconnexion' }).click()
  await page.waitForURL('**/partners/login')

  await page.goto('http://127.0.0.1:5173/admin/login')
  await page.getByLabel('Adresse e-mail').fill('admin@aniek.com')
  await page.locator('#login-password').fill('AniekAdmin2024!')
  await page.getByRole('button', { name: 'Se connecter' }).click()
  await page.waitForURL('**/admin')
  results.adminRedirect = page.url().endsWith('/admin')
  await page.getByRole('navigation', { name: 'Administration' }).getByRole('link', { name: 'Partenaires' }).click()
  await page.getByRole('button', { name: 'Nouveau partenaire' }).click()
  await page.getByLabel('Nom du partenaire').fill('Partenaire de test')
  await page.locator('.editor-modal input[type="file"]').setInputFiles('frontend/public/media/partners/AS-pl.jpg')
  await page.getByRole('button', { name: 'Enregistrer' }).click()
  await page.getByText('Partenaire de test', { exact: true }).waitFor()
  results.adminCanCreatePartner = await page.locator('.admin-table tbody tr').filter({ hasText: 'Partenaire de test' }).count() === 1
  await page.getByRole('button', { name: 'Déconnexion' }).click()
  await page.waitForURL('**/admin/login')
  results.adminLogoutRedirect = page.url().endsWith('/admin/login')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:5173/')
  results.mobileHasNoHorizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
  results.brokenImages = await page.locator('img').evaluateAll((images) => images.filter((image) => !image.complete || image.naturalWidth === 0).map((image) => image.src))
  return results
}